// Generates THIRD_PARTY_NOTICES.md from the installed production dependency tree.
// Run with `npm run notices` after changing dependencies.
import { execSync } from 'node:child_process'
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const root = new URL('..', import.meta.url).pathname
const tree = JSON.parse(execSync('npm ls --omit=dev --all --json', { cwd: root, maxBuffer: 1e8 }).toString())

// Packages whose tarball ships no license file. Text points to the upstream source instead of guessing it.
const noFile = (license, source) =>
  `No license file is shipped in the npm package; its package.json declares ${license}.\nSee ${source}`
const missingTextNotes = {
  '@react-three/fiber': noFile('MIT', 'https://github.com/pmndrs/react-three-fiber/blob/master/LICENSE'),
  // The packages below come with @react-three/drei; tree-shaking keeps them out of the build.
  '@mediapipe/tasks-vision': noFile('Apache-2.0', 'https://github.com/google-ai-edge/mediapipe/blob/master/LICENSE'),
  draco3d: noFile('Apache-2.0', 'https://github.com/google/draco/blob/main/LICENSE'),
  maath: noFile('MIT', 'https://github.com/pmndrs/maath/blob/main/LICENSE'),
  'stats-gl': noFile('MIT', 'https://github.com/RenaudRohlinger/stats-gl/blob/main/LICENSE'),
}

// Packages whose package.json has no license field; taken from the license file they ship.
const licenseOverrides = { 'webgl-constants': 'MIT' }

// Type-only packages never reach the bundle.
const isTypeOnly = (name) => name.startsWith('@types/') || name === 'csstype'

const packages = new Map()
;(function walk(node) {
  for (const [name, dep] of Object.entries(node.dependencies ?? {})) {
    // Unmet optional peers (e.g. the many validators @hookform/resolvers supports) have no version.
    if (!dep.version || dep.missing || isTypeOnly(name) || packages.has(name)) continue
    const dir = join(root, 'node_modules', name)
    const pkg = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'))
    const licenseFile = readdirSync(dir).find((f) => /^(licen[sc]e|copying)/i.test(f))
    packages.set(name, {
      version: dep.version,
      license: typeof pkg.license === 'string' ? pkg.license : (licenseOverrides[name] ?? 'UNKNOWN'),
      homepage: pkg.homepage ?? `https://www.npmjs.com/package/${name}`,
      text: licenseFile ? readFileSync(join(dir, licenseFile), 'utf8').trim() : (missingTextNotes[name] ?? null),
    })
    walk(dep)
  }
})(tree)

const sorted = [...packages].sort(([a], [b]) => a.localeCompare(b))
const unknown = sorted.filter(([, p]) => p.license === 'UNKNOWN' || !p.text)

let md = `# Third-party notices

This project bundles the open-source packages listed below. Each one keeps its own license, which is **not** this repository's MIT license unless stated otherwise.

_Generated by \`npm run notices\` from the installed production dependencies. Do not edit by hand._

## Typography: Geist and Geist Mono (SIL OFL 1.1)

[Geist](https://github.com/vercel/geist-font) and Geist Mono, © 2023 Vercel, are licensed under the [SIL Open Font License 1.1](https://openfontlicense.org/). The latin subsets are bundled into the build from the \`@fontsource/geist\` and \`@fontsource/geist-mono\` packages, listed below with the full license text.

## Original work

The favicon (\`public/favicon.svg\`), UI components, database schema and demo data are original work made for this project and are covered by the MIT license.

## npm packages

| Package | Version | License |
| --- | --- | --- |
${sorted.map(([n, p]) => `| [${n}](${p.homepage}) | ${p.version} | ${p.license} |`).join('\n')}

## License texts
`

for (const [name, p] of sorted) {
  if (!p.text) continue
  md += `\n### ${name}@${p.version}\n\n\`\`\`\n${p.text}\n\`\`\`\n`
}

writeFileSync(join(root, 'THIRD_PARTY_NOTICES.md'), md)
console.log(`Wrote ${sorted.length} packages to THIRD_PARTY_NOTICES.md`)
if (unknown.length) {
  console.warn(`Missing license metadata or text: ${unknown.map(([n]) => n).join(', ')}`)
  process.exitCode = 1
}
